#!/usr/bin/env python3
"""HLSL to C++ for sync_check: one shader source or shader header in, the same code out with what
C++ has no syntax for replaced. The lines stay where they are, so a line number in a report of the
check is a line number of the shader source.

  to_cpp.py <in.hlsl|in.h> <out.gen.h> [<out.entry.h>]

What changes:
  - [numthreads(..)], [loop], [unroll], [branch], [flatten], semantics and register bindings go;
  - 'void main(' becomes 'void shader_main(';
  - a constant buffer becomes a namespace, and the arrays in constant buffers and structs become
    CbArray (they can be indexed out of range without harm, as on a GPU);
  - 'groupshared T name[N][M];' becomes 'static GsArray<T, (N), (M)> name;' (group memory that
    watches its readers and writers);
  - '#include "x.h"' becomes '#include "x.gen.h"', an 'out' parameter a reference;
  - a few spellings C++ does not take ('.x' of a scalar).
The entry file gets the thread group size, a function that calls the shader for one thread of one
group with the system values its parameters ask for, and a function that fills the group memory of
the shader with garbage.
"""
import os
import re
import sys


def convert(text, name):
    lines = text.split('\n')
    out = []
    depth_stack = []  # brace depths at which a constant buffer or struct was opened
    depth = 0
    groupshared = []
    for line in lines:
        code = line
        code = re.sub(r'\[numthreads\([^\]]*\)\]', '', code)
        code = re.sub(r'\[(unroll|loop|branch|flatten)\]', '', code)
        code = re.sub(r':\s*SV_[A-Za-z]+', '', code)
        code = re.sub(r':\s*register\([a-z0-9]+\)', '', code)
        code = re.sub(r'\bvoid main\(', 'void shader_main(', code)
        code = re.sub(r'#include "([A-Za-z0-9_]+)\.h"', r'#include "\1.gen.h"', code)
        code = re.sub(r'\bout\s+(\w+)\s+(\w+)(?=\s*[,)])', r'\1 &\2', code)  # an out parameter

        m = re.match(r'^(\s*)groupshared\s+(\w+)\s+(\w+)((?:\[[^\]]+\])+);(.*)$', code)
        if m:
            dims = re.findall(r'\[([^\]]+)\]', m.group(4))
            code = '%sstatic GsArray<%s, %s> %s;%s' % (m.group(1), m.group(2), ', '.join('(%s)' % d for d in dims),
                                                      m.group(3), m.group(5))
            groupshared.append(m.group(3))

        opens_block = re.match(r'^\s*(cbuffer|struct|typedef\s+struct)\b', code) is not None
        if opens_block:
            depth_stack.append(depth)
        code = re.sub(r'^(\s*)cbuffer\s+\w+\s*\{', r'\1namespace {', code)
        if depth_stack:
            # An array member: 'T name[A][B];' is 'CbArray<CbArray<T, (B)>, (A)> name;'.
            def member(m):
                dims = re.findall(r'\[([^\]]+)\]', m.group(4))
                kind = m.group(2)
                for d in reversed(dims):
                    kind = 'CbArray<%s, (%s)>' % (kind, d)
                return '%s%s %s;' % (m.group(1), kind, m.group(3))
            code = re.sub(r'(^\s*|[{;]\s*)((?:unsigned\s+)?\w+)\s+(\w+)((?:\[[^\]]+\])+);', member, code)
        depth += code.count('{') - code.count('}')
        while depth_stack and depth <= depth_stack[-1]:
            depth_stack.pop()
        out.append(code)
    text = '\n'.join(out)

    # Spellings C++ does not take. Each is tied to the declaration that makes it one.
    if re.search(r'\bint r = residuals\.Load\(', text):
        text = re.sub(r'\br\.x\b', 'r', text)
    text = re.sub(r'(int2 filter_line2_hbd\(.*?\n\})', lambda m: re.sub(r'\bl1\.x\b', 'l1', m.group(1)), text, flags=re.S)
    return text, groupshared


def entry(text, groupshared):
    m = re.search(r'\[numthreads\(([^\]]*)\)\]\s*(?:\\\s*)?void\s+main\s*\(([^{]*)\)\s*(?:\\\s*)?\{', text, flags=re.S)
    if not m:
        return None
    threads = [t.strip() for t in m.group(1).split(',')]
    params = re.sub(r'\\\s*\n', ' ', m.group(2))
    args = []
    for p in params.split(','):
        pm = re.match(r'\s*(\w+)\s+\w+\s*:\s*(SV_\w+)\s*$', p)
        if not pm:
            raise SystemExit('to_cpp.py: parameter not understood: %r' % p)
        kind, semantic = pm.group(1), pm.group(2)
        if semantic == 'SV_DispatchThreadID':
            args.append('%s(group.x * kThreadsX + local.x, group.y * kThreadsY + local.y, group.z * kThreadsZ + local.z)' % kind)
        elif semantic == 'SV_GroupID':
            args.append('%s(group.x, group.y, group.z)' % kind)
        elif semantic == 'SV_GroupThreadID':
            args.append('%s(local.x, local.y, local.z)' % kind)
        elif semantic == 'SV_GroupIndex':
            args.append('(%s)(local.x + local.y * kThreadsX + local.z * kThreadsX * kThreadsY)' % kind)
        else:
            raise SystemExit('to_cpp.py: semantic not known: %s' % semantic)
    lines = ['// Generated by to_cpp.py.',
             'enum { kThreadsX = (%s), kThreadsY = (%s), kThreadsZ = (%s) };' % tuple(threads),
             'static void shader_entry(uint3 group, uint3 local) { shader_main(%s); }' % ', '.join(args),
             'static void shader_scramble(uint64_t *state) {']
    for g in groupshared:
        lines.append('  scramble_bytes(%s.bytes(), %s.byte_size(), state);' % (g, g))
    lines.append('  (void)state;')
    lines.append('}')
    lines.append('static const int kGroupMemoryArrays = %d;' % len(groupshared))
    return '\n'.join(lines) + '\n'


def main():
    if len(sys.argv) < 3:
        raise SystemExit(__doc__)
    text = open(sys.argv[1], encoding='utf-8', errors='replace').read()
    converted, groupshared = convert(text, sys.argv[1])
    if converted.count('\n') != text.count('\n'):
        raise SystemExit('to_cpp.py: the line count changed')
    open(sys.argv[2], 'w', encoding='utf-8').write(converted)
    if len(sys.argv) > 3:
        e = entry(text, groupshared)
        if e is None:
            # The entry point of the transforms is a macro of their common header.
            for header in re.findall(r'#include "([A-Za-z0-9_]+\.h)"', text):
                path = os.path.join(os.path.dirname(sys.argv[1]), header)
                e = entry(open(path, encoding='utf-8', errors='replace').read(), groupshared)
                if e is not None:
                    break
        if e is None:
            raise SystemExit('to_cpp.py: no entry point in %s' % sys.argv[1])
        open(sys.argv[3], 'w', encoding='utf-8').write(e)


if __name__ == '__main__':
    main()
